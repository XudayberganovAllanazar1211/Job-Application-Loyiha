import unittest
from decimal import Decimal

from pg_compat import PostgreSQLCursor, translate_sql, _replace_qmark_placeholders, _adapt_money_params


class FakeCursor:
    def __init__(self):
        self.rows = []
        self.query = ""
        self.closed = False

    def execute(self, query, params=()):
        self.query = query
        self.rows = [(41,)] if "RETURNING id" in query.upper() else [("ok",)]
        return self

    def executemany(self, query, params):
        self.query = query
        return self

    def fetchone(self):
        return self.rows.pop(0) if self.rows else None

    def fetchmany(self, size=None):
        size = size or 1
        rows, self.rows = self.rows[:size], self.rows[size:]
        return rows

    def fetchall(self):
        rows, self.rows = self.rows, []
        return rows

    @property
    def rowcount(self):
        return 1

    @property
    def description(self):
        return None

    def close(self):
        self.closed = True


class CursorCompatibilityTests(unittest.TestCase):
    def test_lastrowid_is_returning_id_and_row_remains_fetchable(self):
        raw = FakeCursor()
        cursor = PostgreSQLCursor(raw)
        cursor.execute("INSERT INTO users(username) VALUES(?)", ("tester",))
        self.assertEqual(cursor.lastrowid, 41)
        self.assertEqual(cursor.fetchone(), (41,))

    def test_reusing_cursor_does_not_leak_previous_lastrowid(self):
        raw = FakeCursor()
        cursor = PostgreSQLCursor(raw)
        cursor.execute("INSERT INTO users(username) VALUES(?)", ("tester",))
        self.assertEqual(cursor.lastrowid, 41)
        cursor.execute("SELECT 1")
        self.assertIsNone(cursor.lastrowid)


class SQLTranslationTests(unittest.TestCase):
    def test_qmark_placeholders_ignore_quoted_text_and_comments(self):
        sql = "SELECT ?, '?' AS literal, \"?\" AS quoted -- ?\nWHERE id=?"
        self.assertEqual(
            _replace_qmark_placeholders(sql),
            "SELECT %s, '?' AS literal, \"?\" AS quoted -- ?\nWHERE id=%s",
        )

    def test_sqlite_null_safe_is(self):
        self.assertEqual(
            translate_sql("SELECT id FROM services WHERE parent_id IS ?"),
            "SELECT id FROM services WHERE parent_id IS NOT DISTINCT FROM %s",
        )

    def test_insert_or_ignore(self):
        result = translate_sql(
            "INSERT OR IGNORE INTO favorites(user_id,target_id) VALUES(?,?)"
        )
        self.assertIn("INSERT INTO favorites", result)
        self.assertIn("ON CONFLICT DO NOTHING", result)
        self.assertIn("VALUES(%s,%s)", result)

    def test_group_concat_and_like(self):
        result = translate_sql(
            "SELECT GROUP_CONCAT(name, ', ') FROM services WHERE name LIKE ?"
        )
        self.assertIn("STRING_AGG(name, ', ')", result)
        self.assertIn("name ILIKE %s", result)

    def test_identity_and_financial_numeric_types(self):
        result = translate_sql(
            "CREATE TABLE payments(id INTEGER PRIMARY KEY AUTOINCREMENT, "
            "amount REAL NOT NULL, balance REAL DEFAULT 0)"
        )
        self.assertIn("BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY", result)
        self.assertIn("amount NUMERIC(18,2)", result)
        self.assertIn("balance NUMERIC(18,2)", result)

    def test_table_info_uses_information_schema(self):
        result = translate_sql("PRAGMA table_info(users)")
        self.assertIn("information_schema.columns", result)
        self.assertIn("current_schema()", result)
        self.assertIn("table_name = %s", result)

    def test_table_existence_uses_information_schema(self):
        result = translate_sql(
            "SELECT name FROM sqlite_master WHERE type='table' AND name='payments'"
        )
        self.assertIn("information_schema.tables", result)
        self.assertIn("table_name = 'payments'", result)

    def test_money_float_parameters_are_converted_to_decimal(self):
        result = _adapt_money_params(
            "UPDATE users SET balance=balance-? WHERE id=?",
            (123.45, 7),
        )
        self.assertEqual(result, (Decimal("123.45"), 7))

    def test_non_money_float_parameters_are_left_as_float(self):
        result = _adapt_money_params(
            "INSERT INTO typing_states(job_id,user_id,updated_at) VALUES(?,?,?)",
            (5, 8, 123.456),
        )
        self.assertEqual(result, (5, 8, 123.456))
        self.assertIsInstance(result[2], float)


if __name__ == "__main__":
    unittest.main()
