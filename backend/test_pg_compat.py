import unittest

from pg_compat import translate_sql, _replace_qmark_placeholders


class SQLTranslationTests(unittest.TestCase):
    def test_qmark_placeholders_ignore_quoted_text_and_comments(self):
        sql = "SELECT ?, '?' AS literal, \"?\" AS quoted -- ?\nWHERE id=?"
        self.assertEqual(
            _replace_qmark_placeholders(sql),
            "SELECT %s, '?' AS literal, \"?\" AS quoted -- ?\nWHERE id=%s",
        )

    def test_sqlite_null_safe_is(self):
        self.assertEqual(
            translate_sql("SELECT id FROM services WHERE parent_id IS ?"),
            "SELECT id FROM services WHERE parent_id IS NOT DISTINCT FROM %s",
        )

    def test_insert_or_ignore(self):
        result = translate_sql(
            "INSERT OR IGNORE INTO favorites(user_id,target_id) VALUES(?,?)"
        )
        self.assertIn("INSERT INTO favorites", result)
        self.assertIn("ON CONFLICT DO NOTHING", result)
        self.assertIn("VALUES(%s,%s)", result)

    def test_group_concat_and_like(self):
        result = translate_sql(
            "SELECT GROUP_CONCAT(name, ', ') FROM services WHERE name LIKE ?"
        )
        self.assertIn("STRING_AGG(name, ', ')", result)
        self.assertIn("name ILIKE %s", result)

    def test_identity_and_financial_numeric_types(self):
        result = translate_sql(
            "CREATE TABLE payments(id INTEGER PRIMARY KEY AUTOINCREMENT, "
            "amount REAL NOT NULL, balance REAL DEFAULT 0)"
        )
        self.assertIn("BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY", result)
        self.assertIn("amount NUMERIC(18,2)", result)
        self.assertIn("balance NUMERIC(18,2)", result)

    def test_table_info_uses_information_schema(self):
        result = translate_sql("PRAGMA table_info(users)")
        self.assertIn("information_schema.columns", result)
        self.assertIn("current_schema()", result)
        self.assertIn("table_name = %s", result)

    def test_table_existence_uses_information_schema(self):
        result = translate_sql(
            "SELECT name FROM sqlite_master WHERE type='table' AND name='payments'"
        )
        self.assertIn("information_schema.tables", result)
        self.assertIn("table_name = 'payments'", result)


if __name__ == "__main__":
    unittest.main()
